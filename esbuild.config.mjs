// Builds main.js from src/, and styles.css from src/styles.css plus the terminal's CSS
// (src/vault-terminal/, with xterm 6's nested under its class).
//   node esbuild.config.mjs             watch
//   node esbuild.config.mjs production  one build
//   node esbuild.config.mjs test        the terminal's Node harness, into .build/
// Both are build output, not tracked. main.js stays readable: no minifying, no tree
// shaking, no sourcemap.
// Options go through withVaultTerminal (src/vault-terminal/build.mjs, PORTING.md), which
// adds the terminal's helper loader, XTERM_VERSION, and xterm's browser check.
import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { vaultTerminalStyles, withVaultTerminal } from "./src/vault-terminal/build.mjs";
import { noticeComment } from "./scripts/notices.mjs";

const mode = process.argv[2] ?? "dev";

const external = [
  "obsidian",
  "electron",
  "@codemirror/*",
  "@lezer/*",
  ...builtinModules,
  ...builtinModules.map((m) => `node:${m}`),
];

export const options = withVaultTerminal({
  // "use strict" first: an ES module is strict, but the CommonJS output esbuild writes
  // from it is not unless the file says so.
  // Then the bundled packages' licenses, since an install gets only the built files.
  banner: { js: `"use strict";\n// Built by esbuild from src/. Edit src/, never this file.\n${noticeComment()}` },
  entryPoints: ["src/main.js"],
  bundle: true,
  external,
  format: "cjs",
  platform: "node",
  target: "es2020",
  charset: "utf8",
  logLevel: "info",
  sourcemap: false,
  treeShaking: false,
  minify: false,
  outfile: "main.js",
  // Not tsconfig.json, which is for the typecheck: its "strict" would make esbuild add a
  // second "use strict". Only the setting its ES2022 target implies for the terminal's
  // TypeScript, class fields as defined properties.
  tsconfigRaw: { compilerOptions: { useDefineForClassFields: true } },
});

// What styles.css holds: Agent Manager's own CSS, then the terminal's.
export function styles() {
  const header = "/* Generated by esbuild.config.mjs from src/styles.css and src/vault-terminal/ (with @xterm/xterm's CSS). Edit those, never this file. */\n";
  return `${header}${noticeComment()}\n\n${readFileSync("src/styles.css", "utf8").trim()}\n\n/* The terminal (src/vault-terminal/) */\n${vaultTerminalStyles()}`;
}
const writeStyles = () => writeFileSync("styles.css", styles());

// Imported by scripts/verify.mjs for the options; run directly to build.
if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (mode === "test") {
    await esbuild.build(withVaultTerminal({
      bundle: true, external, format: "cjs", platform: "node", target: "es2022", logLevel: "info",
      entryPoints: ["test/harness.ts"], outfile: ".build/harness.cjs", sourcemap: "inline",
    }));
  } else if (mode === "production") {
    writeStyles();
    const result = await esbuild.build(options);
    if (result.warnings.length) process.exit(1);
  } else {
    writeStyles();
    const ctx = await esbuild.context({ ...options, plugins: [...options.plugins, { name: "styles", setup(b) { b.onEnd(() => writeStyles()); } }] });
    await ctx.watch();
  }
}
