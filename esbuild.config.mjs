import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { pathToFileURL } from "node:url";
import { vaultTerminalStyles, withVaultTerminal } from "./src/vault-terminal/build.mjs";
import { noticeComment } from "./scripts/notices.mjs";

const mode = process.argv[2] ?? "dev";

const external = [
  "obsidian",
  "electron",
  "@codemirror/*",
  "@lezer/*",
  ...builtinModules,
  ...builtinModules.map((m) => `node:${m}`),
];

const MOD_ROOT = "claude-mod";
function modFiles(dir = MOD_ROOT) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (name === "tsconfig.json" || name === "README.md" || name === ".DS_Store") continue;
    if (name === "types" && dir.endsWith(".claude-plugin")) continue;
    if (statSync(path).isDirectory()) out.push(...modFiles(path));
    else out.push(path);
  }
  return out;
}
const claudeMod = {
  name: "claude-mod-files",
  setup(build) {
    build.onResolve({ filter: /^claude-mod-files$/ }, () => ({ path: "claude-mod-files", namespace: "claude-mod" }));
    build.onLoad({ filter: /.*/, namespace: "claude-mod" }, () => {
      const mods = readdirSync(MOD_ROOT).sort().filter((n) => n !== ".claude-plugin" && statSync(join(MOD_ROOT, n)).isDirectory());
      const files = mods.flatMap((m) => modFiles(join(MOD_ROOT, m)));
      const map = Object.fromEntries(files.map((f) => [relative(MOD_ROOT, f), readFileSync(f, "utf8")]));
      return { contents: `export default ${JSON.stringify(map)};`, loader: "js", watchFiles: files };
    });
  },
};

const GUIDES_ROOT = "guides";
const guideFiles = {
  name: "guide-files",
  setup(build) {
    build.onResolve({ filter: /^guide-files$/ }, () => ({ path: "guide-files", namespace: "guides" }));
    build.onLoad({ filter: /.*/, namespace: "guides" }, () => {
      const files = readdirSync(GUIDES_ROOT).sort().filter((n) => n.endsWith(".md")).map((n) => join(GUIDES_ROOT, n));
      const map = Object.fromEntries(files.map((f) => [relative(GUIDES_ROOT, f), readFileSync(f, "utf8")]));
      map["README.md"] = readFileSync("README.md", "utf8");
      return { contents: `export default ${JSON.stringify(map)};`, loader: "js", watchFiles: [...files, "README.md"], watchDirs: [GUIDES_ROOT] };
    });
  },
};

const SKILLS_ROOT = "skills";
function skillFiles(dir = SKILLS_ROOT) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    if (name === ".DS_Store") continue;
    const path = join(dir, name);
    if (statSync(path).isDirectory()) out.push(...skillFiles(path));
    else out.push(path);
  }
  return out;
}
const starterSkills = {
  name: "skill-files",
  setup(build) {
    build.onResolve({ filter: /^skill-files$/ }, () => ({ path: "skill-files", namespace: "skills" }));
    build.onLoad({ filter: /.*/, namespace: "skills" }, () => {
      const files = skillFiles();
      const map = Object.fromEntries(files.map((f) => [relative(SKILLS_ROOT, f), readFileSync(f, "utf8")]));
      return { contents: `export default ${JSON.stringify(map)};`, loader: "js", watchFiles: files, watchDirs: [SKILLS_ROOT] };
    });
  },
};

export const options = withVaultTerminal({
  plugins: [claudeMod, guideFiles, starterSkills],
  banner: { js: `"use strict";\n// Built by esbuild from src/. Edit src/, never this file.\n${noticeComment()}` },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external,
  format: "cjs",
  platform: "node",
  target: "es2020",
  charset: "utf8",
  logLevel: "info",
  sourcemap: false,
  treeShaking: false,
  minify: false,
  outfile: "main.js",
  tsconfigRaw: { compilerOptions: { useDefineForClassFields: true } },
});

export function styles() {
  const header = "/* Generated by esbuild.config.mjs from src/styles.css and src/vault-terminal/ (with @xterm/xterm's CSS). Edit those, never this file. */\n";
  return `${header}${noticeComment()}\n\n${readFileSync("src/styles.css", "utf8").trim()}\n\n/* The terminal (src/vault-terminal/) */\n${vaultTerminalStyles()}`;
}
const writeStyles = () => writeFileSync("styles.css", styles());

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (mode === "test") {
    await esbuild.build(withVaultTerminal({
      bundle: true, external, format: "cjs", platform: "node", target: "es2022", logLevel: "info",
      entryPoints: ["test/harness.ts"], outfile: ".build/harness.cjs", sourcemap: "inline",
    }));
  } else if (mode === "production") {
    writeStyles();
    const result = await esbuild.build(options);
    if (result.warnings.length) process.exit(1);
  } else {
    writeStyles();
    const ctx = await esbuild.context({ ...options, plugins: [...options.plugins, { name: "styles", setup(b) { b.onEnd(() => writeStyles()); } }] });
    await ctx.watch();
  }
}
