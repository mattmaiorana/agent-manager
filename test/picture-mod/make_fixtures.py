# Writes the test mod's two known pictures, as PNG files
# for the file-path source and as base64 PNG and RGBA bytes in
# hooks/fixtures.js for the byte sources. Standard library only.
#   python3 test/picture-mod/make_fixtures.py
import base64
import os
import struct
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
W, H = 96, 64


def picture_a():
    # Four quadrants: red, green / blue, yellow. Opaque.
    px = bytearray()
    for y in range(H):
        for x in range(W):
            left, top = x < W // 2, y < H // 2
            r, g, b = (255, 0, 0) if left and top else (0, 200, 0) if top else (0, 0, 255) if left else (255, 220, 0)
            px += bytes((r, g, b, 255))
    return px


def picture_b():
    # An 8-pixel checkerboard of magenta and cyan. Opaque.
    px = bytearray()
    for y in range(H):
        for x in range(W):
            on = ((x // 8) + (y // 8)) % 2 == 0
            px += bytes((255, 0, 255, 255) if on else (0, 255, 255, 255))
    return px


def png(rgba, w, h):
    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    raw = b"".join(b"\x00" + bytes(rgba[y * w * 4:(y + 1) * w * 4]) for y in range(h))
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def main():
    a, b = picture_a(), picture_b()
    os.makedirs(os.path.join(HERE, "pictures"), exist_ok=True)
    out = {}
    for name, px in (("a", a), ("b", b)):
        data = png(px, W, H)
        with open(os.path.join(HERE, "pictures", name + ".png"), "wb") as f:
            f.write(data)
        out[name] = (base64.b64encode(data).decode(), base64.b64encode(bytes(px)).decode())
    lines = ["// Generated by make_fixtures.py. Do not edit.", "export const WIDTH = %d;" % W, "export const HEIGHT = %d;" % H]
    for name, (p, r) in out.items():
        lines.append('export const PNG_%s = "%s";' % (name.upper(), p))
        lines.append('export const RGBA_%s = "%s";' % (name.upper(), r))
    with open(os.path.join(HERE, "hooks", "fixtures.js"), "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
